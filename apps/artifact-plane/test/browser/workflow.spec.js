import {test,expect} from '@playwright/test';
import {mkdir,writeFile,rm} from 'node:fs/promises';
import {join} from 'node:path';
import {fixtureRepository,orderingFixture,fingerprint,git} from '../fixtures.js';

test('B12-B14: workflow branches, evidence commits, unknown approval, worktree opening and view preservation',async({page})=>{
 const fixture=await fixtureRepository(orderingFixture());
 const other=fixture.root+'-worktree with space', missing=fixture.root+'-missing';
 const spec='docs/artifacts/knowledge/changes/change-next/specifications/new.md';
 await mkdir(join(fixture.root,spec,'..'),{recursive:true});
 await writeFile(join(fixture.root,spec),'# New contract\n\n## Self-check\nPassed.');
 git(fixture.root,'add','.');
 git(fixture.root,'-c','user.name=Fixture','-c','user.email=fixture@example.invalid','commit','-qm','Define new explorer contract');
 const id=git(fixture.root,'rev-parse','HEAD');
 git(fixture.root,'worktree','add','-qb','feature/workflow',other);
 git(fixture.root,'worktree','add','-q','--detach',missing);
 await rm(missing,{recursive:true,force:true});
 const before=await fingerprint(fixture.root),otherBefore=await fingerprint(other);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 try {
  await page.goto('/');await page.getByLabel('Repository path').fill(fixture.root);
  await page.getByRole('button',{name:'Open repository'}).click();
  await page.getByRole('navigation',{name:'Artifacts'}).getByRole('button',{name:/Knowledge/}).click();
  await page.getByRole('button',{name:'Expand Knowledge',exact:true}).click();
  await page.getByRole('button',{name:'Requirements in Knowledge',exact:true}).click();
  await page.locator('.react-flow__node-element').first().click();
  const panel=page.getByRole('complementary',{name:'Selection details'});
  await expect(panel.getByRole('heading',{name:'requirements/need.md',exact:true,level:2})).toBeVisible();
  const divider=page.getByRole('separator',{name:'Resize details panel'});
  await divider.focus();await page.keyboard.press('ArrowLeft');
  const width=await divider.getAttribute('aria-valuenow'),viewport=await page.locator('.canvas-surface .react-flow__viewport').getAttribute('style');
  await page.getByRole('button',{name:'Workflow',exact:true}).click();
  const view=page.getByLabel('Local ADD workflows');
  await expect(view.locator('.react-flow')).toBeVisible();
  const selected=view.locator('.workflow-group.selected-worktree');
  await expect(selected).toContainText(fixture.root);
  await expect(view).toContainText('feature/workflow');
  await view.locator('.react-flow__node-worktree').filter({hasText:missing}).click();
  await expect(panel).toContainText('This registered worktree cannot be read.');
  await page.screenshot({path:'test-results/workflow-overview.png',fullPage:true});
  const phase=view.locator('.react-flow__node-phase').filter({has:page.getByText('Specification',{exact:true})}).first();
  await phase.click();
  await expect(panel).toContainText('Define new explorer contract');
  await panel.locator('.workflow-commit').first().locator('summary').click();
  await expect(panel.locator('.full-commit').first()).toHaveText(id);
  const workflowViewport=await view.locator('.react-flow__viewport').getAttribute('style');
  await view.getByRole('button',{name:'Zoom In',exact:true}).click();
  await expect(view.locator('.react-flow__viewport')).not.toHaveAttribute('style',workflowViewport);
  await view.getByRole('button',{name:'Fit View',exact:true}).click();
  await view.locator('.react-flow__node-phase').filter({has:page.getByText('Approval',{exact:true})}).first().click();
  await expect(panel).toContainText('Approval cannot be inferred');
  await page.screenshot({path:'test-results/workflow-wide.png',fullPage:true});
  const wfBeforePan=await view.locator('.react-flow__viewport').getAttribute('style');
  const box=await view.locator('.react-flow__pane').boundingBox();
  await page.mouse.move(box.x+25,box.y+30);await page.mouse.down();await page.mouse.move(box.x+70,box.y+70);await page.mouse.up();
  await expect(view.locator('.react-flow__viewport')).not.toHaveAttribute('style',wfBeforePan);
  const wfRetained=await view.locator('.react-flow__viewport').getAttribute('style');
  await divider.focus();await page.keyboard.press('ArrowLeft');
  await expect(panel.getByRole('heading',{name:'Approval',exact:true})).toBeVisible();
  await page.keyboard.press('ArrowRight');
  await page.getByRole('button',{name:'Refresh',exact:true}).click();
  await expect(page.getByRole('button',{name:'Refresh',exact:true})).toBeEnabled();
  await expect(panel.getByRole('heading',{name:'Approval',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Canvas',exact:true}).click();
  await expect(panel.getByRole('heading',{name:'requirements/need.md',exact:true,level:2})).toBeVisible();
  expect(await divider.getAttribute('aria-valuenow')).toBe(width);
  expect(await page.locator('.canvas-surface .react-flow__viewport').getAttribute('style')).toBe(viewport);
  await page.getByRole('button',{name:'Workflow',exact:true}).click();
  await expect(panel.getByRole('heading',{name:'Approval',exact:true})).toBeVisible();
  expect(await view.locator('.react-flow__viewport').getAttribute('style')).toBe(wfRetained);
  await view.getByRole('heading',{name:'feature/workflow',exact:true}).click();
  await panel.getByRole('button',{name:'Open worktree'}).click();
  await expect(page.getByLabel('Repository path')).toHaveValue(other);
  await expect(view.locator('.workflow-group.selected-worktree')).toContainText('feature/workflow');
  await view.getByTestId('rf__node-'+JSON.stringify([other,'knowledge','change-next','Specification'])).click();
  await expect(panel).toContainText('Define new explorer contract');
  await page.setViewportSize({width:700,height:1000});
  await page.screenshot({path:'test-results/workflow-narrow.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(await fingerprint(fixture.root)).toEqual(before);
  expect(await fingerprint(other)).toEqual(otherBefore);
  await page.setViewportSize({width:1440,height:1000});
  await view.getByTestId('rf__node-'+JSON.stringify([other,'knowledge','change-next'])).click();
  await expect(panel).toContainText('Task evidence');
  await rm(join(other,'docs/artifacts/knowledge/changes/change-next'),{recursive:true,force:true});
  await page.getByRole('button',{name:'Refresh',exact:true}).click();
  await expect(panel.getByRole('heading',{name:'Explore workflow phases'})).toBeVisible();
  expect(errors).toEqual([]);
 } finally {await rm(other,{recursive:true,force:true});await fixture.cleanup();}
});
